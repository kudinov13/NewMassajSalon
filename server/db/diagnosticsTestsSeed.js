function getDefaultResultRanges(maxScore) {
    return [
        { minScore: 0, maxScore: Math.floor(maxScore * 0.25) },
        { minScore: Math.floor(maxScore * 0.25) + 1, maxScore: Math.floor(maxScore * 0.5) },
        { minScore: Math.floor(maxScore * 0.5) + 1, maxScore: Math.floor(maxScore * 0.75) },
        { minScore: Math.floor(maxScore * 0.75) + 1, maxScore },
    ];
}

async function seedResultsForTest(db, testId, slug) {
    const questions = defaultQuestions[slug] || [];
    const maxScore = questions.length * 3;
    const results = defaultResults[slug] || [];
    const ranges = getDefaultResultRanges(maxScore);

    await db.run(`DELETE FROM diagnostic_results WHERE testId = ?`, testId);

    for (let ri = 0; ri < results.length; ri++) {
        const r = results[ri];
        const range = ranges[ri];
        await db.run(
            `INSERT INTO diagnostic_results (testId, minScore, maxScore, title, text, isSeriousProblem, buttonLabel, buttonLink) VALUES (?, ?, ?, ?, ?, ?, ?, ?)`,
            testId, range.minScore, range.maxScore, r.title, r.text, r.isSeriousProblem ? 1 : 0, r.buttonLabel || null, r.buttonLink || "/diagnostics/booking"
        );
    }
}

async function seedDefaultTests(db) {
    const diagnosticTestsExist = await db.get(`SELECT id FROM diagnostic_tests LIMIT 1`);
    if (diagnosticTestsExist) return false;

    for (const test of defaultTests) {
        const testResult = await db.run(
            `INSERT INTO diagnostic_tests (slug, title, subtitle) VALUES (?, ?, ?)`,
            test.slug, test.title, test.subtitle
        );
        const testId = testResult.lastID;

        const questions = defaultQuestions[test.slug] || [];
        for (let qi = 0; qi < questions.length; qi++) {
            const q = questions[qi];
            const qResult = await db.run(
                `INSERT INTO diagnostic_questions (testId, text, sortOrder) VALUES (?, ?, ?)`,
                testId, q.text, qi
            );
            const questionId = qResult.lastID;

            for (let oi = 0; oi < q.options.length; oi++) {
                const [text, score] = q.options[oi];
                await db.run(
                    `INSERT INTO diagnostic_options (questionId, text, score, sortOrder) VALUES (?, ?, ?, ?)`,
                    questionId, text, score, oi
                );
            }
        }

        await seedResultsForTest(db, testId, test.slug);
    }

    return true;
}

module.exports = { seedDefaultTests, seedResultsForTest };
